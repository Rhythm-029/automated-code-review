import type { ReviewComment, Severity } from '../types/api';
import { Copy, Check, AlertCircle, AlertTriangle, Info, Sparkles } from 'lucide-react';
import { useState } from 'react';

interface Props {
  comment: ReviewComment;
  index: number;
}

const SEV_LABELS: Record<Severity, string> = {
  critical: 'Critical',
  high: 'High',
  medium: 'Medium',
  low: 'Low',
  info: 'Info',
};

export function CommentCard({ comment, index }: Props) {
  const [copied, setCopied] = useState(false);

  const copyText = () => {
    const text = `**${comment.title}** (${SEV_LABELS[comment.severity]} - ${comment.category})\n\n${comment.body}${
      comment.suggestion ? `\n\n💡 Suggestion: ${comment.suggestion}` : ''
    }`;
    navigator.clipboard.writeText(text).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    });
  };

  const getSeverityBadgeClass = (sev: Severity) => {
    switch (sev) {
      case 'critical':
      case 'high':
        return 'badge-sev-high';
      case 'medium':
        return 'badge-sev-medium';
      case 'low':
        return 'badge-sev-low';
      case 'info':
      default:
        return 'badge-sev-info';
    }
  };

  const getIconCircle = (sev: Severity) => {
    switch (sev) {
      case 'critical':
      case 'high':
        return (
          <div className="comment-icon-circle icon-circle-red" title="High Severity Risk">
            <AlertCircle size={16} />
          </div>
        );
      case 'medium':
        return (
          <div className="comment-icon-circle icon-circle-amber" title="Medium Severity">
            <AlertTriangle size={16} />
          </div>
        );
      case 'low':
        return (
          <div className="comment-icon-circle icon-circle-blue" title="Low / Maintainability">
            <Info size={16} />
          </div>
        );
      case 'info':
      default:
        return (
          <div className="comment-icon-circle icon-circle-purple" title="Recommendation">
            <Sparkles size={16} />
          </div>
        );
    }
  };

  // Clean demo label from body if present
  const displayBody = comment.body
    .replace('⚠️ DEMO MODE — NOT GENERATED BY A REAL MODEL\n\n', '')
    .trim();

  return (
    <div className="modern-comment-card fade-in" style={{ animationDelay: `${index * 50}ms` }}>
      <div className="comment-card-top-row">
        {getIconCircle(comment.severity)}

        <div className="comment-title-badges">
          <div className="comment-headline">
            <span>{comment.title}</span>
            <span className={getSeverityBadgeClass(comment.severity)}>
              {SEV_LABELS[comment.severity]}
            </span>
            <span className="badge-cat-tag">
              {comment.category.replace('_', ' ').replace(/\b\w/g, (l) => l.toUpperCase())}
            </span>
            {comment.file_path && (
              <span className="badge-cat-tag" style={{ fontFamily: 'var(--font-mono)', opacity: 0.85 }} title={comment.file_path}>
                {comment.file_path.split('/').pop()}
              </span>
            )}
            {comment.line && (
              <span className="badge-cat-tag" style={{ fontFamily: 'var(--font-mono)', color: 'var(--accent)' }}>
                Line {comment.line}
              </span>
            )}
          </div>
        </div>

        <button
          onClick={copyText}
          title="Copy comment to clipboard"
          style={{
            background: 'none',
            border: 'none',
            color: 'var(--text-muted)',
            cursor: 'pointer',
            padding: '4px',
            borderRadius: '4px',
          }}
        >
          {copied ? <Check size={14} color="var(--success)" /> : <Copy size={14} />}
        </button>
      </div>

      <p className="comment-explanation-text">{displayBody}</p>

      {comment.code_snippet && (
        <div
          style={{
            margin: '10px 0',
            padding: '8px 12px',
            background: 'rgba(15, 23, 42, 0.6)',
            borderLeft: '3px solid var(--accent)',
            borderRadius: '4px',
            fontFamily: 'var(--font-mono)',
            fontSize: '12px',
            color: '#e2e8f0',
            whiteSpace: 'pre-wrap',
            overflowX: 'auto',
          }}
        >
          <div
            style={{
              fontSize: '10px',
              textTransform: 'uppercase',
              color: 'var(--text-muted)',
              marginBottom: '4px',
              letterSpacing: '0.05em',
            }}
          >
            Referenced Diff Code
          </div>
          <code>{comment.code_snippet}</code>
        </div>
      )}

      {comment.suggestion && (
        <div className="modern-suggestion-callout">
          <div className="suggestion-header-line">
            <span>💡 Suggestion</span>
          </div>
          <div style={{ lineHeight: 1.5 }}>{comment.suggestion}</div>
        </div>
      )}
    </div>
  );
}
