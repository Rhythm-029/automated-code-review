# ── Fine-tuned engine ──────────────────────────────────────────────────────────

class FinetunedEngine(BaseReviewEngine):
    name = "finetuned"
    mode = EngineMode.real_model

    def __init__(self, checkpoint_path: str) -> None:
        self._path = checkpoint_path
        self._model = None
        self._tokenizer = None
        self._loaded = False

    def load(self) -> None:
        from pathlib import Path

        if not Path(self._path).exists():
            raise RuntimeError(f"Checkpoint not found: {self._path}")

        try:
            from transformers import AutoModelForSeq2SeqLM, AutoTokenizer
            logger.info("Loading fine-tuned model from %s", self._path)
            self._tokenizer = AutoTokenizer.from_pretrained(self._path)
            self._model = AutoModelForSeq2SeqLM.from_pretrained(self._path)
            self._model.eval()
            self._loaded = True
            logger.info("Fine-tuned model loaded successfully")
        except Exception as exc:
            raise RuntimeError(f"Failed to load checkpoint: {exc}") from exc

    def generate_review(
        self,
        patch: str,
        oldf: Optional[str] = None,
        max_comments: int = 5,
        filename: Optional[str] = None,
    ) -> Tuple[List[ReviewComment], str]:
        if not self._loaded:
            self.load()

        import torch

        file_prefix = f"File: {filename}\n" if filename else ""
        context = f"{file_prefix}Review the following code diff:\n{patch[:4096]}"
        if oldf:
            context += f"\nOriginal file:\n{oldf[:1024]}"

        inputs = self._tokenizer(
            context,
            return_tensors="pt",
            max_length=512,
            truncation=True,
        )
        with torch.no_grad():
            out = self._model.generate(
                **inputs,
                max_new_tokens=256,
                num_beams=4,
                early_stopping=True,
            )
        raw = self._tokenizer.decode(out[0], skip_special_tokens=True)
        comments = parse_model_output(raw, max_comments)
        if not comments:
            comments = [
                ReviewComment(
                    title="Code review comment",
                    body=raw or "(model produced empty output)",
                    severity=Severity.info,
                    category=Category.general,
                )
            ]
        return comments, raw

    def get_status(self) -> dict:
        return {
            "engine": self.name,
            "mode": self.mode,
            "loaded": self._loaded,
            "checkpoint_path": self._path,
        }

    def get_model_info(self) -> dict:
        return {"engine": self.name, "checkpoint_path": self._path, "loaded": self._loaded}


# ── Ollama engine (Local LLM) ──────────────────────────────────────────────────

class OllamaEngine(BaseReviewEngine):
    name = "ollama"
    mode = EngineMode.real_model

    def __init__(
        self,
        base_url: str = "http://localhost:11434",
        model: str = "qwen2.5-coder:7b",
        timeout: int = 120,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.model = model
        self.timeout = timeout
        self._loaded = False

    def load(self) -> None:
        try:
            with httpx.Client(timeout=4.0) as client:
                res = client.get(f"{self.base_url}/api/tags")
                if res.status_code == 200:
                    models = [m.get("name", "") for m in res.json().get("models", [])]
                    logger.info("Ollama reachable at %s. Models: %s", self.base_url, models)
                    self._loaded = True
                    return
        except Exception as exc:
            logger.warning("Ollama connection probe failed at %s: %s", self.base_url, exc)
            self._loaded = False

    def generate_review(
        self,
        patch: str,
        oldf: Optional[str] = None,
        max_comments: int = 5,
        filename: Optional[str] = None,
    ) -> Tuple[List[ReviewComment], str]:
        system_instruction = OLLAMA_SYSTEM_INSTRUCTION.format(max_comments=max_comments)

        file_prefix = f"File: {filename}\n" if filename else ""
        user_content = f"{file_prefix}Code diff to review:\n```diff\n{patch}\n```"
        if oldf:
            user_content += f"\n\nOriginal file context:\n```\n{oldf[:3000]}\n```"

        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system_instruction},
                {"role": "user", "content": user_content},
            ],
            "format": "json",
            "stream": False,
            "options": {"temperature": 0.2},
        }

        try:
            with httpx.Client(timeout=float(self.timeout)) as client:
                resp = client.post(f"{self.base_url}/api/chat", json=payload)
                if resp.status_code != 200:
                    raise RuntimeError(f"Ollama returned HTTP {resp.status_code}: {resp.text}")
                res_data = resp.json()
                raw_output = res_data.get("message", {}).get("content", "")
        except httpx.ConnectError as err:
            raise RuntimeError(
                f"Cannot connect to Ollama at {self.base_url}. "
                "Ensure Ollama is running locally and model "
                f"'{self.model}' is installed (`ollama run {self.model}`)."
            ) from err
        except httpx.TimeoutException as err:
            raise RuntimeError(
                f"Ollama timed out after {self.timeout}s while generating review with model '{self.model}'."
            ) from err
        except Exception as exc:
            raise RuntimeError(f"Ollama review inference failed: {exc}") from exc

        comments = parse_model_output(raw_output, max_comments, filename=filename)
        return comments, raw_output

    def get_status(self) -> dict:
        is_reachable = False
        available_models = []
        try:
            with httpx.Client(timeout=3.0) as client:
                res = client.get(f"{self.base_url}/api/tags")
                if res.status_code == 200:
                    is_reachable = True
                    available_models = [m.get("name", "") for m in res.json().get("models", [])]
        except Exception:
            pass

        return {
            "engine": self.name,
            "mode": self.mode,
            "model": self.model,
            "base_url": self.base_url,
            "loaded": is_reachable,
            "ollama_reachable": is_reachable,
            "available_models": available_models,
            "model_present": any(self.model in m for m in available_models),
        }

    def get_model_info(self) -> dict:
        return {
            "engine": self.name,
            "model": self.model,
            "base_url": self.base_url,
        }


# ── Factory ────────────────────────────────────────────────────────────────────

def build_engine(settings) -> BaseReviewEngine:
    """Construct the appropriate engine from settings."""
    engine_name = settings.active_engine
    logger.info("Building review engine: %s", engine_name)

    if engine_name == "groq":
        engine = GroqEngine(
            api_key=settings.GROQ_API_KEY,
            model=settings.GROQ_MODEL,
            timeout=settings.GROQ_TIMEOUT,
        )
        try:
            engine.load()
        except Exception as exc:
            logger.warning("Failed to initialize Groq engine: %s. Falling back to DemoEngine.", exc)
            return DemoEngine()
        return engine

    if engine_name == "ollama":
        engine = OllamaEngine(
            base_url=settings.OLLAMA_BASE_URL,
            model=settings.OLLAMA_MODEL,
            timeout=settings.OLLAMA_TIMEOUT,
        )
        engine.load()
        return engine

    if engine_name == "openai":
        engine = OpenAIEngine(
            api_key=settings.OPENAI_API_KEY,
            model=settings.OPENAI_MODEL,
        )
        engine.load()
        return engine

    if engine_name == "anthropic":
        engine = AnthropicEngine(
            api_key=settings.ANTHROPIC_API_KEY,
            model=settings.ANTHROPIC_MODEL,
        )
        engine.load()
        return engine

    if engine_name == "finetuned":
        engine = FinetunedEngine(checkpoint_path=settings.FINETUNED_MODEL_PATH)
        engine.load()
        return engine

    # Default: demo
    return DemoEngine()
