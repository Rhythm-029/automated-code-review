class DemoEngine(BaseReviewEngine):
    name = "demo"
    mode = EngineMode.demo

    def load(self) -> None:
        pass

    def generate_review(
        self,
        patch: str,
        oldf: Optional[str] = None,
        max_comments: int = 5,
        filename: Optional[str] = None,
    ) -> Tuple[List[ReviewComment], str]:
        n = min(max_comments, len(_DEMO_COMMENTS_POOL))
        selected = []
        for c in _DEMO_COMMENTS_POOL[:n]:
            c_copy = c.model_copy()
            if filename:
                c_copy.file_path = filename
