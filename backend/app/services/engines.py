# ── Helpers ────────────────────────────────────────────────────────────────────

DEMO_BANNER = "⚠️ DEMO MODE — NOT GENERATED BY A REAL MODEL"

_SEVERITY_WORDS = {
    "critical": Severity.critical,
    "high": Severity.high,
    "medium": Severity.medium,
    "low": Severity.low,
    "info": Severity.info,
}

_CATEGORY_WORDS = {
    "correctness": Category.correctness,
    "bug": Category.bug_risk,
    "bug_risk": Category.bug_risk,
    "security": Category.security,
    "performance": Category.performance,
    "readability": Category.readability,
    "maintainability": Category.maintainability,
    "testing": Category.testing,
}


def _infer_severity(text: str) -> Severity:
    lower = text.lower()
    for kw, sev in _SEVERITY_WORDS.items():
        if kw in lower:
            return sev
    if any(w in lower for w in ["critical", "exploit", "cve", "injection", "rce", "remote code"]):
        return Severity.critical
    if any(w in lower for w in ["error", "exception", "crash", "null", "none", "division", "leak", "panic"]):
        return Severity.high
    if any(w in lower for w in ["warn", "could", "might", "consider", "inefficient"]):
        return Severity.medium
    return Severity.low


def _infer_category(text: str) -> Category:
    lower = text.lower()
    for kw, cat in _CATEGORY_WORDS.items():
        if kw in lower:
            return cat
    if any(w in lower for w in ["auth", "xss", "sql", "inject", "token", "password", "secret", "csrf"]):
        return Category.security
    if any(w in lower for w in ["speed", "slow", "complexity", "o(n", "query", "cache", "alloc"]):
        return Category.performance
    if any(w in lower for w in ["test", "coverage", "mock", "assert"]):
        return Category.testing
    return Category.general


def _parse_json_comments(
    raw: str, max_comments: int, filename: Optional[str] = None
) -> List[ReviewComment]:
    """Extract review comments from raw JSON string (array, wrapped dict, or single object)."""
    clean = re.sub(r"```(?:json)?", "", raw).strip()

    parsed_data = None
    try:
        parsed_data = json.loads(clean)
    except json.JSONDecodeError:
        # Try extracting JSON array [...]
        match_arr = re.search(r"\[.*\]", clean, re.DOTALL)
        if match_arr:
            try:
                parsed_data = json.loads(match_arr.group(0))
            except json.JSONDecodeError:
                pass

        if parsed_data is None:
            # Try extracting JSON object {...}
            match_obj = re.search(r"\{.*\}", clean, re.DOTALL)
            if match_obj:
                try:
                    parsed_data = json.loads(match_obj.group(0))
                except json.JSONDecodeError:
                    pass

    if parsed_data is None:
        return []

    items = []
    if isinstance(parsed_data, list):
        items = parsed_data
    elif isinstance(parsed_data, dict):
        for key in ["findings", "comments", "review_comments", "reviews", "results"]:
            if key in parsed_data and isinstance(parsed_data[key], list):
                items = parsed_data[key]
                break
        if not items and ("title" in parsed_data or "body" in parsed_data or "explanation" in parsed_data):
            items = [parsed_data]

    comments: List[ReviewComment] = []
    for item in items[:max_comments]:
        if not isinstance(item, dict):
            continue
        body = item.get("body", item.get("explanation", item.get("comment", item.get("text", ""))))
        title = item.get("title", item.get("summary", item.get("issue_title", body[:60])))
        if not body:
            continue
        sev_raw = item.get("severity", "")
        cat_raw = item.get("category", "")

        line_val = item.get("line", item.get("start_line"))
        if line_val is not None:
            try:
                line_val = int(line_val)
            except (ValueError, TypeError):
                line_val = None

        end_line_val = item.get("end_line")
        if end_line_val is not None:
            try:
                end_line_val = int(end_line_val)
            except (ValueError, TypeError):
                end_line_val = None

        file_path_val = item.get("file_path", item.get("file", filename))
        snippet_val = item.get("code_snippet", item.get("relevant_code", item.get("snippet", item.get("code"))))
        suggestion_val = item.get("suggestion", item.get("recommended_correction", item.get("suggested_code")))
        evidence_val = item.get("evidence_assessment")

        comments.append(
            ReviewComment(
                title=title,
                body=body,
                severity=_SEVERITY_WORDS.get(str(sev_raw).lower(), _infer_severity(body)),
                category=_CATEGORY_WORDS.get(str(cat_raw).lower(), _infer_category(body)),
                suggestion=suggestion_val,
                line=line_val,
                end_line=end_line_val,
                file_path=file_path_val,
                code_snippet=snippet_val,
                evidence_assessment=evidence_val,
                confidence=None,
            )
        )
    return comments


def _parse_plain_comments(
    raw: str, max_comments: int, filename: Optional[str] = None
) -> List[ReviewComment]:
    """Fallback: split by numbered list or paragraph and create comments."""
    parts = re.split(r"(?m)^(?:\d+\.|[-*])\s+", raw)
    parts = [p.strip() for p in parts if p.strip() and len(p.strip()) > 20]

    if len(parts) <= 1:
        parts = [p.strip() for p in raw.split("\n\n") if p.strip() and len(p.strip()) > 20]

    comments: List[ReviewComment] = []
    for part in parts[:max_comments]:
        first_line = part.split("\n")[0][:80].rstrip(".")
        comments.append(
            ReviewComment(
                title=first_line,
                body=part,
                severity=_infer_severity(part),
                category=_infer_category(part),
                file_path=filename,
            )
        )
    return comments


def parse_model_output(
    raw: str, max_comments: int, filename: Optional[str] = None
) -> List[ReviewComment]:
    """Parse model text output into structured comments."""
    if not raw or not raw.strip():
        return []
    # If the output is a valid JSON object or array, parse strictly via JSON
    clean = re.sub(r"```(?:json)?", "", raw).strip()
    if clean.startswith("{") or clean.startswith("["):
        try:
            parsed = json.loads(clean)
            # If JSON parsed successfully and findings/comments is an empty list, respect that
            if isinstance(parsed, dict) and any(k in parsed and parsed[k] == [] for k in ["findings", "comments", "review_comments", "reviews"]):
                return []
            if isinstance(parsed, list) and len(parsed) == 0:
                return []
        except Exception:
            pass

    comments = _parse_json_comments(raw, max_comments, filename=filename)
    if not comments and not (clean.startswith("{") or clean.startswith("[")):
        comments = _parse_plain_comments(raw, max_comments, filename=filename)
    return comments


# ── Base interface ─────────────────────────────────────────────────────────────

class BaseReviewEngine(ABC):
    name: str = "base"
    mode: EngineMode = EngineMode.real_model

    @abstractmethod
    def load(self) -> None: ...

    @abstractmethod
    def generate_review(
        self,
        patch: str,
        oldf: Optional[str] = None,
        max_comments: int = 5,
        filename: Optional[str] = None,
    ) -> Tuple[List[ReviewComment], str]:
        """Return (comments, raw_output)."""
        ...

    def get_status(self) -> dict:
        return {"engine": self.name, "mode": self.mode, "loaded": True}

    def get_model_info(self) -> dict:
        return {"engine": self.name}


